export const CHARACTER_LIST: CharacterDef[] = Object.values(CHARACTERS);

export function getCharacterUnlockCost(characterId: CharacterId): number {
  return Math.max(0, CHARACTERS[characterId]?.unlockCost ?? 0);
}

export function isStarterCharacter(characterId: CharacterId): boolean {
  return STARTER_CHARACTER_IDS.includes(characterId);
}

export function getCharacterCoinBonusAmount(characterId: CharacterId): number {
  const cost = getCharacterUnlockCost(characterId);
  if (cost <= 0) return 0;
  return Math.floor(cost / 100);
}

export function applyCharacterCoinBonus(baseCoins: number, characterId: CharacterId): number {
  if (baseCoins <= 0) return 0;
  return Math.floor(baseCoins) + getCharacterCoinBonusAmount(characterId);
}
